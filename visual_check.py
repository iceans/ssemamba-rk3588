import cv2
import os
import numpy as np


def verify_bboxes(img_path, bboxes, save_path=None):
    """
    在图像上绘制边界框并保存。

    Args:
        img_path (str): 原始图像的绝对路径。
        bboxes (list): 边界框列表，格式假设为 [[x1, y1, x2, y2], ...]。
        save_path (str, optional): 结果保存路径。若为 None，则保存至原目录下 "_verified" 后缀文件。
    """
    # 1. 路径检查
    if not os.path.exists(img_path):
        print(f"[Error] 文件不存在: {img_path}")
        return

    # 2. 读取图像
    # cv2.imread 默认读取 BGR 格式
    img = cv2.imread(img_path)
    img = cv2.resize(img, (640, 338))
    if img is None:
        print(f"[Error] 无法读取图像 (可能是权限或格式问题): {img_path}")
        return

    print(f"[Info] 图像尺寸: {img.shape} (H, W, C)")

    # 3. 绘制边界框
    # 颜色格式: (B, G, R), (0, 255, 0) 为绿色
    color = (0, 255, 0)
    thickness = 2

    for i, box in enumerate(bboxes):
        # 强制转换为 int，OpenCV 绘图需要整数坐标
        # 假设格式: [x_min, y_min, x_max, y_max]
        x1, y1, x2, y2 = map(int, box)

        # 边界保护 (防止框超出图像边缘报错)
        h, w = img.shape[:2]
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(w, x2), min(h, y2)

        # 绘制矩形
        cv2.rectangle(img, (x1, y1), (x2, y2), color, thickness)

        # 可选：添加标签索引
        cv2.putText(img, str(i), (x1, y1 - 5), cv2.FONT_HERSHEY_SIMPLEX, 0.5, color, 1)

    # 4. 保存结果
    if save_path is None:
        name, ext = os.path.splitext(img_path)
        save_path = f"{name}_verified{ext}"

    # 确保保存路径的目录存在
    os.makedirs(os.path.dirname(save_path), exist_ok=True)

    cv2.imwrite(save_path, img)
    print(f"[Success] 验证结果已保存至: {save_path}")


